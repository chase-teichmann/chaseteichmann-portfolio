// Runs after `astro build` (npm run build). Adds the site's security headers:
//
// - dist/_headers: read by the Cloudflare Worker that serves the site (not served as a file).
//   Content-Security-Policy, clickjacking protection, HSTS and friends.
// - A <meta> Content-Security-Policy at the top of every page, so the policy also applies on hosts
//   that can't set headers (GitHub Pages). It's the same policy minus the parts a <meta> tag can't
//   carry (frame-ancestors).
//
// The site has no third-party scripts, but every page runs small inline scripts, so the policy
// allows exactly those by their SHA-256 hashes, computed here from the built pages. Changing an
// inline script changes its hash, and the next build picks it up.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const DIST = new URL('../dist/', import.meta.url).pathname;
const site = JSON.parse(readFileSync(new URL('../src/data/site.json', import.meta.url), 'utf8'));
const booking = new URL(site.bookingEndpoint).origin;

const pages = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (name.endsWith('.html')) pages.push(path);
  }
})(DIST);

// Inline scripts the browser runs: classic and module scripts without src. Data blocks
// (application/json, application/ld+json) never run, so they need no hash.
const RUNS = (attrs) => {
  const type = /\btype\s*=\s*"([^"]*)"/i.exec(attrs)?.[1].trim().toLowerCase();
  return !/\bsrc\s*=/i.test(attrs) && (!type || type === 'module' || type === 'text/javascript' || type === 'application/javascript');
};
const hashes = new Set();
for (const page of pages) {
  const html = readFileSync(page, 'utf8');
  for (const [, attrs, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    if (RUNS(attrs)) hashes.add(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
  }
}

const policy = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].sort().join(' ')}`,
  // Inline <style> blocks and style="" attributes are part of how the pages are built.
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self' data:",
  `connect-src 'self' ${booking}`,
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
];
const metaPolicy = policy.join('; ');
const headerPolicy = [...policy, "frame-ancestors 'none'", 'upgrade-insecure-requests'].join('; ');

for (const page of pages) {
  const html = readFileSync(page, 'utf8');
  if (html.includes('http-equiv="Content-Security-Policy"')) throw new Error(`${page} already has a CSP meta tag`);
  // Right after <meta charset> (which must stay in the first 1,024 bytes) and before any script.
  const out = html.replace(/<meta charset="utf-8">/i, (m) => `${m}<meta http-equiv="Content-Security-Policy" content="${metaPolicy}">`);
  if (out === html) throw new Error(`${page} has no <meta charset="utf-8">`);
  const head = out.slice(0, out.indexOf('<meta http-equiv="Content-Security-Policy"'));
  if (/<script\b/i.test(head)) throw new Error(`${page} runs a script before the CSP meta tag`);
  writeFileSync(page, out);
}

const headers = `# Generated by scripts/csp.mjs after each build. Edit that script, not this file.
/*
  Content-Security-Policy: ${headerPolicy}
  X-Frame-Options: DENY
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()
  Cross-Origin-Opener-Policy: same-origin
  Strict-Transport-Security: max-age=31536000
`;
writeFileSync(join(DIST, '_headers'), headers);
console.log(`csp: ${hashes.size} inline script hashes, ${pages.length} pages, dist/_headers written`);
